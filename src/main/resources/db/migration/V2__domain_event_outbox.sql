-- Outbox de eventos de dominio (#165, ADR 0021). Vale para PostgreSQL (Neon) y para H2 en modo PostgreSQL.
-- Cada evento se guarda en la misma transacción que su agregado; un relé programado lo entrega después.
create table domain_event_outbox (
    id           bigint generated by default as identity primary key,
    event_type   varchar(100)  not null,
    account_id   uuid          not null,
    payload      varchar(4000) not null,
    occurred_on  timestamp(6) with time zone not null,
    recorded_at  timestamp(6) with time zone not null,
    published_at timestamp(6) with time zone,
    attempts     integer       not null default 0,
    failed_at    timestamp(6) with time zone,
    last_error   varchar(1000)
);

create index ix_domain_event_outbox_pending on domain_event_outbox (published_at, failed_at, id);
